"""dciab cluster-values: capi-cluster values for one cluster of a site config.

Exit codes: 0 written, 1 the config or the cluster can't produce values, 2 could not run.
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path as FsPath
from typing import List, Optional


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        prog="dciab cluster-values",
        description="Print the capi-cluster values for one cluster of a validated site config.")
    parser.add_argument("config", help="path to the site config, for example ./dciab.yaml")
    parser.add_argument("cluster", nargs="?", help="mgmt, infra, or a workload cluster name")
    parser.add_argument("--root", required=True, help="the unpacked archive (set by the dciab entrypoint)")
    parser.add_argument("--trust-bundle", metavar="FILE",
                        help="the platform CA (PEM). Default: pki.chain when pki.mode is import-intermediate")
    parser.add_argument("--list", action="store_true", help="list the config's clusters and exit")
    parser.add_argument("-o", "--output", metavar="FILE", help="write the values here (mode 600) instead of stdout")
    args = parser.parse_args(argv)

    try:
        import yaml
    except ImportError:
        print("dciab cluster-values: missing Python module 'yaml' (python3-pyyaml)", file=sys.stderr)
        return 2

    from dciab_validate import checks, schema_check
    from dciab_validate.findings import ERROR
    from dciab_validate.loader import LoadError, load

    from .values import ValuesError, cluster_names, cluster_values, unsupported

    root = FsPath(args.root).resolve()
    config_path = FsPath(args.config)
    try:
        doc, _ = load(config_path.read_text(encoding="utf-8"))
    except OSError as exc:
        print(f"dciab cluster-values: cannot read {config_path}: {exc.strerror}", file=sys.stderr)
        return 2
    except LoadError as exc:
        print(f"dciab cluster-values: {config_path}: {exc.message}", file=sys.stderr)
        return 1

    findings = schema_check.check(doc, schema_check.load_schema(root))
    if not findings:
        findings, _ = checks.run(doc, config_path, root)
    errors = [f for f in findings if f.severity == ERROR]
    if errors:
        print(f"dciab cluster-values: {config_path} is not valid ({len(errors)} errors); "
              f"run: dciab validate {config_path}", file=sys.stderr)
        return 1

    if args.list:
        print("\n".join(cluster_names(doc)))
        return 0
    if not args.cluster:
        print("dciab cluster-values: name the cluster (mgmt, infra, or a workload cluster); --list shows them",
              file=sys.stderr)
        return 2

    try:
        bundle = _trust_bundle(doc, config_path, args.trust_bundle)
        values = cluster_values(doc, args.cluster, bundle)
    except (ValuesError, OSError) as exc:
        print(f"dciab cluster-values: {exc}", file=sys.stderr)
        return 1
    for note in unsupported(doc, args.cluster):
        print(f"dciab cluster-values: warning: {note}", file=sys.stderr)

    header = (f"# capi-cluster values for {args.cluster}, generated by dciab cluster-values from "
              f"{config_path.name}.\n# Regenerate instead of editing.\n")
    text = header + dump(values)
    if args.output:
        fd = os.open(args.output, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write(text)
    else:
        sys.stdout.write(text)
    return 0


def dump(values: dict) -> str:
    """YAML with multi-line strings (the PEM bundle) as literal blocks."""
    import yaml

    class Dumper(yaml.SafeDumper):
        pass

    def str_presenter(dumper, data):
        style = "|" if "\n" in data else None
        return dumper.represent_scalar("tag:yaml.org,2002:str", data, style=style)

    Dumper.add_representer(str, str_presenter)
    return yaml.dump(values, Dumper=Dumper, sort_keys=False, default_flow_style=False)


def _trust_bundle(doc: dict, config_path: FsPath, override: Optional[str]) -> str:
    """The platform CA nodes trust: --trust-bundle, or the imported chain."""
    from .values import ValuesError

    if override:
        return FsPath(override).read_text(encoding="utf-8")
    pki = doc["spec"]["pki"]
    if pki["mode"] == "import-intermediate":
        ref = pki["chain"]
        if "file" in ref:
            raw = ref["file"]
            path = FsPath(raw) if os.path.isabs(raw) else config_path.parent / raw
            return path.read_text(encoding="utf-8")
        return os.environ[ref["env"]]
    raise ValuesError("pki.mode is generate-root: the platform CA doesn't exist until dciab seed creates it; "
                      "pass it with --trust-bundle")
